import express from 'express';
import helmet from 'helmet';
import cors from 'cors';
import hpp from 'hpp';
import mongoSanitize from 'express-mongo-sanitize';
import cookieParser from 'cookie-parser';
import pinoHttp from 'pino-http';
import morgan from 'morgan';
import rateLimit from 'express-rate-limit';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import swaggerUi from 'swagger-ui-express';
import {env} from './config/env.js';
import {logger} from './config/logger.js';
import routes from './routes/index.js';
import {notFound,errorHandler} from './middlewares/errorHandler.js';

export const app=express();
app.disable('x-powered-by');
app.set('trust proxy',1);
app.use((req,res,next)=>{if(env.NODE_ENV==='production'&&!req.secure)return res.status(426).json({success:false,message:'HTTPS is required',code:'HTTPS_REQUIRED',errors:[]});next()});
app.use(helmet());
const allowedOrigins = env.CORS_ORIGIN.split(',').map((origin) => origin.trim());
app.use(cors({ origin: allowedOrigins, credentials: true }));
app.use(express.json({limit:'100kb'}));
app.use(express.urlencoded({extended:false,limit:'100kb'}));
app.use(cookieParser());
app.use(hpp());
app.use(mongoSanitize());
app.use(pinoHttp({logger}));
if(env.NODE_ENV==='development')app.use(morgan('dev'));
const rateLimitHandler=(_req,res)=>res.status(429).json({success:false,message:'Too many requests',code:'RATE_LIMITED',errors:[]});
app.use('/api/v1',rateLimit({windowMs:15*60_000,limit:300,standardHeaders:true,legacyHeaders:false,handler:rateLimitHandler}));
app.use('/api/v1/auth/login',rateLimit({windowMs:15*60_000,limit:10,standardHeaders:true,legacyHeaders:false,handler:rateLimitHandler,keyGenerator:req=>`${req.ip}:${crypto.createHash('sha256').update(String(req.body?.email||'').toLowerCase()).digest('hex')}`}));
app.use('/api/v1/auth/forgot-password',rateLimit({windowMs:60*60_000,limit:5,standardHeaders:true,legacyHeaders:false,handler:rateLimitHandler}));
const specPath=fileURLToPath(new URL('../docs/openapi.yaml',import.meta.url));
app.get('/openapi.yaml',(_req,res)=>res.type('application/yaml').sendFile(specPath));
app.use('/api/docs',swaggerUi.serve,swaggerUi.setup(undefined,{swaggerOptions:{url:'/openapi.yaml'}}));
app.use('/api/v1',routes);
app.use(notFound);
app.use(errorHandler);
